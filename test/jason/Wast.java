	private static final double[] POSITIVE_DECIMAL_POWER = new double[39];
	private static final double[] NEGTIVE_DECIMAL_POWER = new double[64];

	static {
		for (int i = 0; i < POSITIVE_DECIMAL_POWER.length; i++)
			POSITIVE_DECIMAL_POWER[i] = Math.pow(10, i);
		for (int i = 0; i < NEGTIVE_DECIMAL_POWER.length; i++)
			NEGTIVE_DECIMAL_POWER[i] = Math.pow(10, -i);
	}

	private static double scientificToIEEEDouble(final long val, final int scale) {
		if (val <= 0)
			return 0;
		if (scale == 0)
			return val;
		final int i;
		if (scale > 0) {
			if (scale > 342)
				return 0;
			i = scale * 4 - 2;
		} else { // scale < 0
			if (scale > -23 && val <= 0x20_0000_0000_0000L) // 1L << 53
				return val * POSITIVE_DECIMAL_POWER[-scale];
			if (scale < -308)
				return Double.POSITIVE_INFINITY;
			i = -scale * 4 - 4;
		}
		final long y = ED5[i], z = ED5[i + 1];
		final int leadingZeros = Long.numberOfLeadingZeros(val);
		final long x = val << (leadingZeros - 1);
		long h = Math.multiplyHigh(x, y); // h is 61~62 bits
		int sr = h > 0x1fff_ffff_ffff_ffffL ? 9 : 8;
		int e2 = (int)(z >> 48) - scale - leadingZeros + sr;  // e52 + 1075
		if (e2 <= 0) {
			if ((sr += 1 - e2) > 61)
				return 0;
			e2 = 0;
		} else if (e2 > 2046)
			return Double.POSITIVE_INFINITY;
		final long mmask = (1L << sr) - 1, l, y32;
		if ((h & mmask) == (mmask >> 1) && (l = x * y) <= 0
				&& l + ((Math.multiplyHigh(x, (y32 = z & 0xffff_ffffL)) << 32) + ((x * y32) >>> 32)) >= 0) // check whether a carry-over may occur in the lower bits
			h++;
		long mantissa0 = ((h >>> (sr - 1)) + 1) >> 1;
		if (mantissa0 == 1L << 53) {
			mantissa0 = 1L << 52;
			e2++;
		}
		return Double.longBitsToDouble(((long)e2 << 52) + (mantissa0 & ((1L << 52) - 1)));
	}

	public static double parseDoubleWast(final byte[] buf, int pos) {
		int b = buf[pos++];
		final boolean neg;
		if ((neg = (b == '-')) || b == '+')
			b = buf[pos++];
		long v = 0;
		int s = 0, ev = 0, dotPos = 0;
		for (; ; b = buf[pos++]) {
			if (((b - '0') & 0x7fff_ffff) < 10) {
				if (v <= (Long.MAX_VALUE - 9) / 10)
					v = v * 10 + b - '0';
				else if (dotPos == 0)
					s--;
				else
					break;
			} else if (b == '.')
				dotPos = pos + 1;
			else if ((b | 0x20) == 'e') { // b == 'e' || b == 'E'
				if (dotPos != 0) {
					s += pos - dotPos;
					dotPos = 0;
				}
				b = buf[pos++];
				boolean expNeg;
				if ((expNeg = (b == '-')) || b == '+')
					b = buf[pos++];
				for (; ((b - '0') & 0x7fff_ffff) < 10; b = buf[pos++])
					ev = ev * 10 + b - '0';
				if (expNeg)
					ev = -ev;
				break;
			} else
				break;
		}
		if (dotPos != 0)
			s += pos - dotPos;
		final double f = scientificToIEEEDouble(v, s - ev);
		return neg ? -f : f;
	}

	private static float scientificToIEEEFloat(final long val, final int scale) {
		if (scale > 0)
			return scale < 64 ? (float)(val * NEGTIVE_DECIMAL_POWER[scale]) : 0;
		if (scale == 0)
			return val;
		return scale > -39 ? (float)(val * POSITIVE_DECIMAL_POWER[-scale]) : Float.POSITIVE_INFINITY;
	}

